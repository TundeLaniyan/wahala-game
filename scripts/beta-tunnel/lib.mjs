/**
 * Pure helpers of the founder-laptop tunnel launcher (scripts/beta-tunnel.mjs, docs/ops/BETA_TUNNEL_TESTING.md). No I/O, no clock, no
 * process: everything here is unit-tested in tests/ops/beta-tunnel.test.ts. The launcher does the side effects.
 */
import { randomBytes } from 'node:crypto';

/** A Cloudflare Quick Tunnel address as cloudflared prints it. */
export const TUNNEL_URL_RE = /https:\/\/([a-z0-9]+(?:-[a-z0-9]+)+)\.trycloudflare\.com(?![a-z0-9.-])/i;

/** The first quick-tunnel address in some cloudflared output, as `{ url, host }`, or null. */
export function extractTunnelUrl(text) {
  const m = TUNNEL_URL_RE.exec(String(text ?? ''));
  if (!m) return null;
  const host = `${m[1].toLowerCase()}.trycloudflare.com`;
  return { url: `https://${host}`, host };
}

const HOST_RE = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/;
/** A host name that is safe to write into the nginx files (letters, digits, dots, hyphens only). */
export const isSafeHost = (h) => typeof h === 'string' && h.length <= 253 && HOST_RE.test(h);

const EMAIL_RE = /^[^\s@,;<>"'`\\]+@[^\s@,;<>"'`\\]+\.[^\s@,;<>"'`\\]+$/;
export const isEmail = (s) => typeof s === 'string' && s.length <= 254 && EMAIL_RE.test(s.trim());

/** `ada@example.com, Bayo@Example.com` (commas, spaces or new lines) -> unique lower-case addresses; `bad` lists what is not an address. */
export function parseEmails(text) {
  const good = [];
  const bad = [];
  for (const raw of String(text ?? '').split(/[\s,;]+/)) {
    const e = raw.trim().toLowerCase();
    if (!e) continue;
    if (!isEmail(e)) bad.push(raw.trim());
    else if (!good.includes(e)) good.push(e);
  }
  return { good, bad };
}

/** A new private access token: 128 random bits, hex (letters and digits only, so it is safe inside the nginx files and a cookie). */
export const newToken = (bytes = randomBytes) => bytes(16).toString('hex');
export const isToken = (t) => typeof t === 'string' && /^[0-9a-f]{32}$/.test(t);

/** A new invite code in the platform's format (10-64 letters, digits, - or _): `wb-` plus 16 hex characters. */
export const newInviteCode = (bytes = randomBytes) => `wb-${bytes(8).toString('hex')}`;
export const isInviteCode = (c) => typeof c === 'string' && /^[A-Za-z0-9_-]{10,64}$/.test(c);

/**
 * The generated nginx file with the access gate (mounted at /etc/edge/tunnel/gate.conf). Two maps over the SAME token list: one for the
 * cookie that unlocks the site, one for the token in a private link. Nobody listed = nobody gets in (the default of both maps is 0).
 * Throws on anything that is not a token, so nothing but hex can ever reach the file.
 */
export function renderGateConf(tokens) {
  for (const t of tokens) if (!isToken(t)) throw new Error('a gate token must be 32 hex characters');
  const rows = tokens.map((t) => `  "${t}" 1;`).join('\n');
  return [
    "# GENERATED by scripts/beta-tunnel.mjs for this run. Never edit, never commit: it holds the testers' private tokens.",
    'map $cookie_wahala_gate $gate_ok {',
    '  default 0;',
    rows,
    '}',
    'map $arg_k $enter_ok {',
    '  default 0;',
    rows,
    '}',
    '',
  ].join('\n');
}

/** The generated nginx file naming the one host that is served (mounted at /etc/edge/tunnel/host.conf). */
export function renderHostConf(host) {
  if (!isSafeHost(host)) throw new Error(`not a safe host name: ${host}`);
  return [
    '# GENERATED by scripts/beta-tunnel.mjs for this run: the tunnel address that is served; every other Host gets a 421.',
    'map $host $host_ok {',
    '  default 0;',
    `  "${host}" 1;`,
    '}',
    '',
  ].join('\n');
}

/** The compose settings file for one run (non-secret). `origin` is the tunnel's https address. */
export function renderTunnelEnv({ origin, port, stateDir, distDir, uid, gid }) {
  if (!/^https:\/\/[a-z0-9.-]+$/.test(origin))
    throw new Error('origin must be an https address without a path');
  if (!Number.isInteger(port) || port < 1024 || port > 65535) throw new Error('port must be 1024-65535');
  return [
    '# GENERATED by scripts/beta-tunnel.mjs for this run (non-secret settings; the secrets are files in secrets/).',
    `GAME_ORIGINS=${origin}`,
    `PUBLIC_WEB_URL=${origin}`,
    'PLATFORM_GUEST_ONLY=1',
    'INVITE_ONLY=1',
    `TUNNEL_PORT=${port}`,
    '# capacity: the measured limit of docs/ops/BETA_LOAD_RESULTS.md (two matches at once); do not raise without new measurements',
    'RUMBLE_MAX_PLAYING_ROOMS=2',
    'RUMBLE_CPU_BUDGET=70',
    'BACKUP_HOUR_UTC=3',
    'BACKUP_KEEP_DAYS=7',
    `BETA_UID=${uid}`,
    `BETA_GID=${gid}`,
    `BETA_STATE=${stateDir}`,
    `GAME_DIST=${distDir}`,
    '',
  ].join('\n');
}

/** The private link for one tester: opens the gate, then redirects to the game. */
export const testerLink = (url, token) => `${url}/__enter?k=${token}`;

/** `2.24.0`, `v2.29.1-desktop.1`, `Docker Compose version v5.6.1` -> [major, minor, patch] or null. */
export function parseVersion(text) {
  const m = /(\d+)\.(\d+)(?:\.(\d+))?/.exec(String(text ?? ''));
  return m ? [Number(m[1]), Number(m[2]), Number(m[3] ?? 0)] : null;
}
/** True when version `have` is at least `need` (both [major, minor, patch]). */
export function versionAtLeast(have, need) {
  if (!have) return false;
  for (let i = 0; i < 3; i++) {
    if (have[i] !== need[i]) return have[i] > need[i];
  }
  return true;
}

/** Does this `cloudflared tunnel --help` text list the `--allowed-mail` option? (Detected, never assumed: docs/ops/BETA_TUNNEL_TESTING.md.) */
export const helpMentionsAllowedMail = (helpText) => /--allowed-mail\b/.test(String(helpText ?? ''));

/** One line of the edge's access log -> { when, ip, method, route, status, seconds } or null. Mirrors the `ops` log format in nginx.tunnel.conf. */
export function parseEdgeLine(line) {
  const m = /^(\S+) (\S+) "(\S+) (\S+)" (\d{3}) ([\d.]+) /.exec(line.replace(/^\S+\s+\|\s+/, ''));
  if (!m) return null;
  return { when: m[1], ip: m[2], method: m[3], route: m[4], status: Number(m[5]), seconds: Number(m[6]) };
}

/** A short summary of edge lines: requests per route class and how many were refused (403 gate, 421 host, 429 limit, 404). */
export function summariseEdge(lines) {
  const out = {
    total: 0,
    byRoute: {},
    refused: { gate403: 0, wrongHost421: 0, limited429: 0, notFound404: 0 },
    serverErrors: 0,
  };
  for (const l of lines) {
    const e = parseEdgeLine(l);
    if (!e) continue;
    out.total++;
    out.byRoute[e.route] = (out.byRoute[e.route] ?? 0) + 1;
    if (e.status === 403) out.refused.gate403++;
    else if (e.status === 421) out.refused.wrongHost421++;
    else if (e.status === 429) out.refused.limited429++;
    else if (e.status === 404) out.refused.notFound404++;
    else if (e.status >= 500) out.serverErrors++;
  }
  return out;
}
