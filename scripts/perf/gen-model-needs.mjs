// Derives src/render/assets/modelNeeds.generated.ts from a real-browser recording (scripts/perf/asset-access.mjs run on a
// build that preloads every model). Rules (docs/MOBILE_PERFORMANCE.md "On-demand models"):
//   - an arena needs every model id its build touched (touched non-prefix ids);
//   - a prefix whose consumer indexes into the LOADED list (`n++ % ids.length`: env_building_*, env_wall*) needs its WHOLE
//     group, or the layout would change; pillars and soft props intersect with the arena's style list, so they are stable;
//   - every match needs the generator and all four vehicles (they appear at any time during play), whatever a short run saw.
//   node scripts/perf/gen-model-needs.mjs tools/perf/model-access.eager.json > src/render/assets/modelNeeds.generated.ts
import fs from 'node:fs';
import path from 'node:path';

const input = JSON.parse(fs.readFileSync(process.argv[2] ?? 'tools/perf/model-access.eager.json', 'utf8'));
const modelDir = 'src/assets/models';
const ids = [
  ...fs.readdirSync(modelDir).filter((f) => f.endsWith('.glb')),
  ...fs.readdirSync(path.join(modelDir, 'lazy')).filter((f) => f.endsWith('.glb')),
].map((f) => f.replace(/\.glb$/, ''));
const FULL_GROUPS = ['env_building_', 'env_wall'];
const ALWAYS = ['gen_generator', 'veh_danfo', 'veh_taxi', 'veh_keke', 'veh_okada'];
const BOOT = new Set(['char_streetBaller', 'char_campusQueen', 'char_lekkiBoy', 'char_areaBoss']);
const out = {};
for (const [arena, touched] of Object.entries(input).sort(([a], [b]) => a.localeCompare(b))) {
  const set = new Set(ALWAYS);
  for (const t of touched) {
    if (!t.endsWith('*')) {
      if (ids.includes(t)) set.add(t);
    } else if (FULL_GROUPS.includes(t.slice(0, -1))) {
      for (const id of ids) if (id.startsWith(t.slice(0, -1))) set.add(id);
    }
  }
  out[arena] = [...set].filter((id) => !BOOT.has(id)).sort();
}
const lines = Object.entries(out).map(([a, list]) => `  ${a}: [${list.map((i) => `'${i}'`).join(', ')}],`);
process.stdout
  .write(`// GENERATED by scripts/perf/gen-model-needs.mjs from tools/perf/model-access.eager.json. Do not edit by hand:
// re-record with scripts/perf/asset-access.mjs and regenerate (docs/MOBILE_PERFORMANCE.md).
export const GENERATED_ARENA_MODELS: Readonly<Record<string, readonly string[]>> = {
${lines.join('\n')}
};
`);
