#!/usr/bin/env python3
"""Writes the candidate manifest for the seven district songs from make_districts.py's report.json:
tracks (standard + Data Saver file, start-offset variants, bar grid, family), the arena map, per-family Sudden Death.
usage: make_district_manifest.py DIR"""
import json, os, sys
d = sys.argv[1]
rep = json.load(open(os.path.join(d, "report.json")))
ZIP_HASHES = {  # SHA-256 of the founder's MP3s (pack manifest of 2026-11-24, verified)
    "ojuelegba": "2a9efe2bad8d14f567c35eeac67b20652611661d6109efeedf3368872492b4e8", "oshodi": "69d7b869bcad923be1af08a377b23a7e99022dfd67f384c2253714771c5196e0",
    "mushin": "5e681205240c20f47ffd320a886e38c182ae33335f5cebaddd03287fc3e11e2c", "fadeyi": "2225031e5500418f734645f7eba40529197aac21a6ca9dce16204031988f3edd",
    "ebute": "a4e16a3ff9aedad0bcba86b162741e27bcfdea9f51d4002aec53f80363f7a9d9", "lagosisland": "5f489756d375f90608f5d2b03260180c0373217963044edf8290247b2269c366",
    "lekki": "37aa90c591d8dfea1d12889da3390573f1f431bdf36fe5d137d5e88ef53c51a3"}
LIC = ("CANDIDATE, NOT approved. Generated by the founder with Gemini; commercial-use rights of the recording and of this mastered derivative are "
       "unverified; do not ship before founder listening approval and a rights decision (docs/AUDIO_DISTRICTS.md).")
tracks, arena_map, sd_for = [], {}, {}
for did, r in rep.items():
    m, sd, loop = r["master"], r["suddenDeath"], r["loop"]; first = 0.0
    for v in ("a", "b", "c", "d"):
        tracks.append(dict(id=f"dist_{did}_{v}", title=f"{r['title']} ({r['district']}), start point {v.upper()}", artist=None,
                           source=f"Gemini-generated, founder pack 2026-11-24, {r['sourceFile']} (SHA-256 {ZIP_HASHES[did][:16]}...)",
                           licence=LIC, file=f"dist_{did}.mp3", lite=f"lite/dist_{did}.mp3", approved=False, gain=1.0, loudnessLufs=m["lufs"],
                           startAt=r["variantStartsSec"][v], grid={"bpm": r["bpm"], "first": first}, family=did, seconds=loop["seconds"], bytes=m["bytes"], liteBytes=m["liteBytes"]))
    tracks.append(dict(id=f"dist_{did}_sd", title=f"{r['title']}: Sudden Death loop ({sd['bars']} bars, same tempo)", artist=None,
                       source="derived from the same recording (loudest section plus tension layers)", licence=LIC, file=f"dist_{did}_sd.mp3", lite=f"lite/dist_{did}_sd.mp3",
                       approved=False, gain=1.0, loudnessLufs=sd["lufs"], grid={"bpm": r["bpm"], "first": 0.0}, family=did, seconds=sd["seconds"], bytes=sd["bytes"], liteBytes=sd["liteBytes"]))
    sd_for[did] = f"dist_{did}_sd"
    arena_map[r["arena"]] = {"tracks": [f"dist_{did}_a", f"dist_{did}_b"], "start": f"dist_{did}_a"}
# standard arenas that share a district get a distinct start point of the same song (applied in ?audiodraft=match)
SHARED = {"oshodiInterchange": ("oshodi", "c"), "lekkiRoadworks": ("lekki", "c"), "balogunMarket": ("lagosisland", "c")}
for arena, (did, v) in SHARED.items():
    if did in rep: arena_map[arena] = {"tracks": [f"dist_{did}_{v}"], "start": f"dist_{did}_{v}"}
# proposals NOT applied: weaker geographic fits, for the founder to accept or refuse
PROPOSED = {"yabaAfterDark": ("fadeyi", "c", "medium"), "surulerePowerYard": ("mushin", "c", "medium"), "thirdMainland": ("ebute", "c", "weak"), "lagoonJetty": ("lagosisland", "d", "medium")}
manifest = {
    "_comment": "UNAPPROVED candidates (decision AU3): the seven district songs, mastered. One file per song, four start points (a-d) of its seamless loop, a Sudden Death loop on the song's own tempo. Merged with the Lagos No Dey Sleep manifest by tools/audio/candidates/stage.mjs; read only with ?audiodraft.",
    "version": 2, "approvalStatus": "candidates-awaiting-founder-listening", "tracks": tracks, "playlists": {"default": [], "arenas": {}}, "menu": [],
    "arenaMap": arena_map, "variants": {"suddenDeathFor": sd_for},
    "proposedNotApplied": {a: {"track": f"dist_{d}_{v}", "district": d, "fit": f} for a, (d, v, f) in PROPOSED.items()},
}
json.dump(manifest, open(os.path.join(d, "manifest.json"), "w"), indent=2)
print("manifest:", len(tracks), "tracks,", len(arena_map), "arenas mapped")
