#!/usr/bin/env python3
"""
Voice-line importer: founder-approved WAV voice clips -> the game's voice registry.

Inputs (all inside this folder, committed):
  founder_manifest.json   the founder's voice plan (WAHALA_NIGERIAN_AUDIO_PACK_V1): every planned line with its
                          trigger event, zone, priority, cooldown, mix bus, persona and transcript
  masters/<id>.wav        the approved masters (16-bit PCM WAV, mono). The file name is the manifest `filename`.

Outputs (regenerated from scratch on every run, so the result depends only on the inputs above):
  public/audio/voices/voices.json        the line catalogue the game reads (voice lines only, sound effects excluded)
  public/audio/voices/recorded.json      the clips that exist, with their licence statement, length and loudness
  public/audio/voices/recorded/<id>.mp3  browser-friendly encodes (MP3, mono, 24 kHz, 64 kbps; Safari/iOS, Chrome,
                                         Firefox and Android all decode MP3 with decodeAudioData)

Adding the next batch (see docs/AUDIO.md "Adding voice clips"):
  python3 tools/audio/voices/import_voices.py --add /path/to/new_wavs
copies every WAV whose name matches a planned, non-rejected manifest line into masters/ and rebuilds the outputs.
`--manifest new_manifest.json` replaces founder_manifest.json first (when the founder updates the plan).

Each master is validated (PCM 16-bit, mono, 16-48 kHz, 0.3-8 s, not silent, not clipped), its leading/trailing
silence trimmed to ~40 ms, loudness-matched to TARGET_LUFS (gain capped, peaks limited to PEAK_DB) with ffmpeg,
then encoded. Lines whose status is REJECTED are never imported, whatever files are present.

Requires python3 with numpy, and ffmpeg (with libmp3lame) on PATH.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
MASTERS = HERE / 'masters'
FOUNDER = HERE / 'founder_manifest.json'
OUT = ROOT / 'public' / 'audio' / 'voices'

#: Integrated loudness every clip is matched to (EBU R128). Urgent/ambient levels are set at runtime.
TARGET_LUFS = -16.0
#: Peak ceiling after loudness matching (the limiter keeps the few loud syllables under it).
PEAK_DB = -1.5
#: Never raise a quiet clip by more than this (dB): it would only lift noise.
MAX_BOOST_DB = 8.0
#: Silence kept before the first / after the last syllable (seconds).
PAD_S = 0.04
SILENCE = 0.01  # linear amplitude below which a 10 ms frame counts as silence
BITRATE = '64k'

LICENSE = (
    'Synthetic voice generated by the founder with Google Gemini API text-to-speech '
    '(prebuilt voice {voice}); founder-approved for WAHALA!. Gemini API Additional Terms of Service apply; '
    'see public/audio/LICENSES.md'
)

#: Founder mix bus -> game voice bus.
BUS = {'VO_REACTION': 'reaction', 'VO_CROWD': 'crowd', 'VO_AMBIENT': 'ambient'}
#: Founder spatial zone -> game zone. Which arenas belong to a zone is data in voices.json (`zones`).
ZONE = {'ALL': 'all', 'DANFO_BUS_PARK': 'bus_park', 'BALOGUN_MARKET': 'market'}
#: Initial arena membership of the location zones (kept from the existing voices.json once it exists).
DEFAULT_ZONES = {
    'bus_park': ['danfoBusPark', 'oshodiInterchange', 'cityRumble', 'rumbleOshodi', 'rumbleOjuelegba', 'rumbleApapa'],
    'market': [
        'balogunMarket',
        'oshodiInterchange',
        'yabaAfterDark',
        'cityRumble',
        'rumbleOshodi',
        'rumbleLagosIsland',
        'rumbleOjuelegba',
    ],
}
SAFE_ID = re.compile(r'^[A-Za-z0-9_-]+$')


def fail(msg: str) -> None:
    print(f'error: {msg}', file=sys.stderr)
    sys.exit(1)


def voice_lines(manifest: dict) -> list[dict]:
    """The founder's voice lines (the environmental sound-effect requests are not voices)."""
    return [a for a in manifest['assets'] if a.get('mix_bus') in BUS]


def is_rejected(line: dict) -> bool:
    return 'REJECT' in str(line.get('status', '')).upper()


def read_wav(path: Path) -> tuple[np.ndarray, int]:
    with wave.open(str(path)) as w:
        if w.getcomptype() != 'NONE':
            raise ValueError('not PCM')
        if w.getsampwidth() != 2:
            raise ValueError(f'{w.getsampwidth() * 8}-bit, expected 16-bit')
        if w.getnchannels() != 1:
            raise ValueError(f'{w.getnchannels()} channels, expected mono')
        sr = w.getframerate()
        if not 16000 <= sr <= 48000:
            raise ValueError(f'{sr} Hz, expected 16-48 kHz')
        data = np.frombuffer(w.readframes(w.getnframes()), dtype='<i2').astype(np.float64) / 32768.0
    return data, sr


def validate(data: np.ndarray, sr: int) -> None:
    dur = len(data) / sr
    if not 0.3 <= dur <= 8.0:
        raise ValueError(f'{dur:.2f} s long, expected 0.3-8 s')
    peak = float(np.abs(data).max()) if len(data) else 0.0
    if peak < 0.05:
        raise ValueError('silent or nearly silent')
    clipped = int((np.abs(data) >= 0.999).sum())
    if clipped > 8:
        raise ValueError(f'{clipped} clipped samples')


def trim(data: np.ndarray, sr: int) -> np.ndarray:
    hop = max(1, sr // 100)
    frames = [np.sqrt(np.mean(data[i : i + hop] ** 2)) for i in range(0, len(data) - hop + 1, hop)]
    loud = [i for i, e in enumerate(frames) if e > SILENCE]
    if not loud:
        return data
    pad = int(PAD_S * sr)
    start = max(0, loud[0] * hop - pad)
    end = min(len(data), (loud[-1] + 1) * hop + pad)
    return data[start:end]


def write_wav(path: Path, data: np.ndarray, sr: int) -> None:
    pcm = np.clip(np.round(data * 32767.0), -32768, 32767).astype('<i2')
    with wave.open(str(path), 'wb') as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(sr)
        w.writeframes(pcm.tobytes())


def loudness(path: Path) -> float:
    """Integrated loudness (LUFS) measured by ffmpeg's EBU R128 meter."""
    r = subprocess.run(
        ['ffmpeg', '-hide_banner', '-nostats', '-i', str(path), '-af', 'ebur128', '-f', 'null', '-'],
        capture_output=True,
        text=True,
        check=True,
    )
    found = re.findall(r'I:\s+(-?[\d.]+) LUFS', r.stderr)
    if not found:
        raise ValueError('ffmpeg could not measure loudness')
    return float(found[-1])


def peak_db(path: Path) -> float:
    """Sample peak (dBFS) of an encoded file, as decoded by ffmpeg."""
    r = subprocess.run(
        ['ffmpeg', '-hide_banner', '-nostats', '-i', str(path), '-af', 'astats=measure_overall=Peak_level', '-f', 'null', '-'],
        capture_output=True,
        text=True,
        check=True,
    )
    found = re.findall(r'Peak level dB:\s+(-?[\d.]+|-inf)', r.stderr)
    if not found:
        raise ValueError('ffmpeg could not measure the peak')
    return float(found[-1]) if found[-1] != '-inf' else -120.0


def encode(src: Path, dst: Path, gain_db: float) -> None:
    limit = 10 ** (PEAK_DB / 20)
    fade = 0.01
    with wave.open(str(src)) as w:
        dur = w.getnframes() / w.getframerate()
    chain = (
        f'volume={gain_db:.2f}dB,'
        f'alimiter=limit={limit:.4f}:attack=2:release=40:level=0,'
        f'afade=t=in:d={fade},afade=t=out:st={max(0.0, dur - fade):.3f}:d={fade},'
        'aresample=24000'
    )
    subprocess.run(
        [
            'ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-i', str(src), '-af', chain,
            '-ac', '1', '-ar', '24000', '-c:a', 'libmp3lame', '-b:a', BITRATE,
            '-map_metadata', '-1', '-fflags', '+bitexact', '-flags:a', '+bitexact', str(dst),
        ],
        check=True,
    )


def catalogue(manifest: dict, zones: dict) -> dict:
    personas = manifest.get('personas', {})
    lines = []
    for a in voice_lines(manifest):
        line_id = Path(a['filename']).stem
        persona = personas.get(a.get('speaker_persona'), {})
        lines.append(
            {
                'id': line_id,
                'trigger': a['trigger_event'],
                'bus': BUS[a['mix_bus']],
                'zone': ZONE.get(a.get('spatial_zone', 'ALL'), 'all'),
                'priority': int(a.get('priority', 3)),
                'cooldown': float(a.get('cooldown_sec', 5)),
                'text': a['transcript'],
                'speaker': a.get('speaker_persona', 'unknown'),
                'speakerLabel': persona.get('label', ''),
                'status': 'rejected' if is_rejected(a) else 'planned',
            }
        )
    return {
        'version': 2,
        'note': (
            'Voice-line catalogue generated by tools/audio/voices/import_voices.py from the founder manifest. '
            'A line only plays when recorded.json lists an approved clip for it; rejected lines never play. '
            'These are synthetic Gemini text-to-speech voices, not recordings of people.'
        ),
        'source': f"{manifest.get('package_name', '?')} {manifest.get('version', '?')}",
        'zones': zones,
        'lines': lines,
    }


def build() -> None:
    manifest = json.loads(FOUNDER.read_text())
    lines = {Path(a['filename']).stem: a for a in voice_lines(manifest)}
    personas = manifest.get('personas', {})
    previous = OUT / 'voices.json'
    zones = DEFAULT_ZONES
    if previous.exists():
        old = json.loads(previous.read_text())
        if isinstance(old.get('zones'), dict):
            zones = old['zones']

    rec_dir = OUT / 'recorded'
    rec_dir.mkdir(parents=True, exist_ok=True)
    for old in rec_dir.glob('*.mp3'):
        old.unlink()

    clips = []
    problems = []
    with tempfile.TemporaryDirectory() as tmp:
        for master in sorted(MASTERS.glob('*.wav')):
            line_id = master.stem
            line = lines.get(line_id)
            if line is None:
                problems.append(f'{master.name}: no line with this filename in the founder manifest')
                continue
            if is_rejected(line):
                problems.append(f'{master.name}: the line is REJECTED; it is never imported')
                continue
            if not SAFE_ID.match(line_id):
                problems.append(f'{master.name}: unsafe name')
                continue
            try:
                data, sr = read_wav(master)
                validate(data, sr)
            except ValueError as e:
                problems.append(f'{master.name}: {e}')
                continue
            trimmed = Path(tmp) / f'{line_id}.wav'
            write_wav(trimmed, trim(data, sr), sr)
            measured = loudness(trimmed)
            gain = min(MAX_BOOST_DB, TARGET_LUFS - measured)
            out = rec_dir / f'{line_id}.mp3'
            encode(trimmed, out, gain)
            with wave.open(str(trimmed)) as w:
                duration = w.getnframes() / w.getframerate()
            voice = personas.get(line.get('speaker_persona'), {}).get('gemini_voice', 'unknown')
            clips.append(
                {
                    'id': line_id,
                    'file': out.name,
                    'license': LICENSE.format(voice=voice),
                    'speaker': line.get('speaker_persona', 'unknown'),
                    'duration': round(duration, 3),
                    'sourceLufs': round(measured, 1),
                    'gainDb': round(gain, 1),
                    'peakDb': round(peak_db(out), 1),
                }
            )
            print(f'  {line_id:28s} {duration:5.2f} s  {measured:6.1f} LUFS -> {gain:+5.1f} dB  {out.stat().st_size:6d} B')

    (OUT / 'voices.json').write_text(json.dumps(catalogue(manifest, zones), indent=2, ensure_ascii=False) + '\n')
    recorded = {
        'version': 2,
        '_comment': (
            'Approved voice clips (synthetic Gemini TTS voices supplied by the founder), generated by '
            'tools/audio/voices/import_voices.py. Do not edit by hand: add masters and re-run the importer.'
        ),
        'clips': clips,
    }
    (OUT / 'recorded.json').write_text(json.dumps(recorded, indent=2, ensure_ascii=False) + '\n')
    planned = [k for k, v in lines.items() if not is_rejected(v)]
    print(f'{len(clips)} of {len(planned)} planned voice lines have an approved clip.')
    for p in problems:
        print(f'  skipped {p}')


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--manifest', type=Path, help='replace founder_manifest.json with this file first')
    ap.add_argument('--add', type=Path, help='folder of new WAV masters to copy into masters/ first')
    args = ap.parse_args()
    if shutil.which('ffmpeg') is None:
        fail('ffmpeg is not on PATH')
    if args.manifest:
        json.loads(args.manifest.read_text())  # must parse
        shutil.copyfile(args.manifest, FOUNDER)
    MASTERS.mkdir(exist_ok=True)
    if args.add:
        manifest = json.loads(FOUNDER.read_text())
        lines = {Path(a['filename']).stem: a for a in voice_lines(manifest)}
        # only the top level of the folder: a `rejected/` subfolder is never looked at
        for wav in sorted(args.add.glob('*.wav')):
            line = lines.get(wav.stem)
            if line is None or is_rejected(line):
                print(f'  not imported: {wav.name} ({"rejected" if line else "not in the manifest"})')
                continue
            shutil.copyfile(wav, MASTERS / wav.name)
            print(f'  added {wav.name}')
    build()


if __name__ == '__main__':
    main()
