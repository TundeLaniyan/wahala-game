"""Writes docs/VOICE_RECORDING_SCRIPT.md: every crowd line with its id, trigger and text, for voice actors.

    python3 tools/audiogen/export_script.py
"""
from pathlib import Path

import pidgin_script as P

WHEN = {
    "match_start": "the match begins",
    "gen_placed": "someone puts down a generator",
    "fuse": "a generator next to the player is about to blow (shouted warning)",
    "escape": "the player escapes a blast / a near miss",
    "elim_bot": "an opponent is eliminated (blast)",
    "elim_human": "the player is eliminated (blast)",
    "danfo": "a Danfo attacks (launch / warning / near miss / eliminates someone)",
    "taxi": "a taxi attacks (same triggers)",
    "keke": "a Keke attacks (same triggers)",
    "vehicle_destroyed": "a vehicle is destroyed",
    "okada_save": "the player's Okada takes a lethal hit and saves them",
    "okada_break": "an opponent's Okada is destroyed",
    "final": "the last 30 seconds begin / the last 10 seconds",
    "win": "the player wins",
    "lose": "the player loses",
    "draw": "the match is a draw",
    "kicked": "a generator is kicked or thrown",
    "pickup": "the player grabs a rare pickup",
    "pushed": "someone is pushed",
    "thrown": "a bottle / firecracker is thrown from the crowd",
    "crush": "a block crushes down on the arena",
    "hazard": "someone hits a pothole or oil",
    "dazed": "someone is dazed",
}

out = ["# Voice recording script", "",
       "Every crowd line currently in the game. The shipped audio for these lines is **synthetic placeholder speech**",
       "(see `docs/AUDIO.md`); recordings by Nigerian speakers should replace it. Generated by",
       "`tools/audiogen/export_script.py` from `tools/audiogen/pidgin_script.py`; do not edit by hand.", "",
       "Recording and integration steps: `public/audio/voices/recorded/README.md`.", "",
       "Direction: ordinary people in a busy Lagos bus park / market, not announcers. Vary age, gender and region of",
       "accent across speakers; reactions are shouted or exclaimed over noise, ambient lines are conversational.", "",
       "## Gameplay reactions", "", "| Clip id | Category | When it plays | Line |", "| --- | --- | --- | --- |"]
for cat, lines in P.REACTIONS.items():
    for i, text in enumerate(lines):
        out.append(f"| `r_{cat}_{i}` | {cat} | {WHEN[cat]} | {text} |")
out += ["", "## Street conversations and calls (ambient)", "",
        "Scenes are played line after line by DIFFERENT speakers; `call` scenes are shouted from a distance.", "",
        "| Clip id | Scene | Kind | Line |", "| --- | --- | --- | --- |"]
for sc in P.AMBIENT:
    for i, text in enumerate(sc["lines"]):
        out.append(f"| `a_{sc['id']}_{i}` | {sc['id']} | {sc['kind']} | {text} |")
Path(__file__).resolve().parents[2].joinpath("docs/VOICE_RECORDING_SCRIPT.md").write_text("\n".join(out) + "\n")
print("wrote", sum(len(v) for v in P.REACTIONS.values()) + sum(len(s["lines"]) for s in P.AMBIENT), "lines")
